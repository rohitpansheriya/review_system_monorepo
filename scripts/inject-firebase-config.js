#!/usr/bin/env node
/**
 * scripts/inject-firebase-config.js
 *
 * Reads Firebase env vars from the root .env file (or from the real
 * environment, e.g. in CI) and writes review_page/firebase-config.js.
 *
 * Usage (local dev):
 *   node scripts/inject-firebase-config.js
 *
 * Usage (CI / GitHub Actions — env vars already set as secrets):
 *   node scripts/inject-firebase-config.js
 *
 * The output file is gitignored; run this script before serving or
 * deploying the review page.
 */

"use strict";

const fs = require("fs");
const path = require("path");

// Load .env from the repo root (silently ignore if running in CI where
// env vars are injected directly by the runner).
const envPath = path.resolve(__dirname, "../.env");
if (fs.existsSync(envPath)) {
  const lines = fs.readFileSync(envPath, "utf8").split("\n");
  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const [key, ...rest] = trimmed.split("=");
    if (key && !(key in process.env)) {
      process.env[key] = rest.join("=");
    }
  }
}

const required = [
  "FIREBASE_API_KEY",
  "FIREBASE_AUTH_DOMAIN",
  "FIREBASE_PROJECT_ID",
  "FIREBASE_STORAGE_BUCKET",
  "FIREBASE_MESSAGING_SENDER_ID",
  "FIREBASE_APP_ID",
];

const missing = required.filter((k) => !process.env[k]);
if (missing.length > 0) {
  console.error("❌  Missing required env vars:", missing.join(", "));
  console.error("    Copy .env.example → .env and fill in real values.");
  process.exit(1);
}

const config = {
  apiKey: process.env.FIREBASE_API_KEY,
  authDomain: process.env.FIREBASE_AUTH_DOMAIN,
  projectId: process.env.FIREBASE_PROJECT_ID,
  storageBucket: process.env.FIREBASE_STORAGE_BUCKET,
  messagingSenderId: process.env.FIREBASE_MESSAGING_SENDER_ID,
  appId: process.env.FIREBASE_APP_ID,
  ...(process.env.FIREBASE_MEASUREMENT_ID
    ? { measurementId: process.env.FIREBASE_MEASUREMENT_ID }
    : {}),
};

const output = `// AUTO-GENERATED by scripts/inject-firebase-config.js — do not edit by hand.
// This file is gitignored. Re-run the script after changing .env.
window.__FIREBASE_CONFIG__ = ${JSON.stringify(config, null, 2)};
`;

const outPath = path.resolve(__dirname, "../review_page/firebase-config.js");
fs.writeFileSync(outPath, output, "utf8");
console.log("✅  Wrote review_page/firebase-config.js");
